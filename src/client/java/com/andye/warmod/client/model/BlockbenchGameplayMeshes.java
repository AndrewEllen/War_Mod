    private static final class Cube {
        private final float x0, y0, z0, x1, y1, z1, ox, oy, oz;
        private final float sinX, cosX, sinY, cosY, sinZ, cosZ;
        private final int red, green, blue, materialIndex;
        private final boolean emissive;

        private Cube(float x0, float y0, float z0, float x1, float y1, float z1,
            float ox, float oy, float oz, float rotationX, float rotationY, float rotationZ,
            int red, int green, int blue, int materialIndex, boolean emissive) {
            this.x0=x0; this.y0=y0; this.z0=z0; this.x1=x1; this.y1=y1; this.z1=z1;
            this.ox=ox; this.oy=oy; this.oz=oz;
            float rx=(float)Math.toRadians(rotationX), ry=(float)Math.toRadians(rotationY), rz=(float)Math.toRadians(rotationZ);
            sinX=(float)Math.sin(rx); cosX=(float)Math.cos(rx);
            sinY=(float)Math.sin(ry); cosY=(float)Math.cos(ry);
            sinZ=(float)Math.sin(rz); cosZ=(float)Math.cos(rz);
            this.red=red; this.green=green; this.blue=blue; this.materialIndex=materialIndex; this.emissive=emissive;
        }

        private void render(PoseStack.Pose pose, VertexConsumer buffer, float scale,
            float originX, float originY, float originZ, int light, int alpha) {
            renderBounds(pose,buffer,x0,y0,z0,x1,y1,z1,scale,originX,originY,originZ,light,alpha);
        }

        private void renderQuarter(PoseStack.Pose pose, VertexConsumer buffer, float scale,
            float originX, float originY, float originZ, int light, int alpha, int quarter) {
            boolean positiveX = quarter == 0 || quarter == 3;
            boolean positiveZ = quarter == 0 || quarter == 1;
            float qx0=positiveX?Math.max(x0,0):x0, qx1=positiveX?x1:Math.min(x1,0);
            float qz0=positiveZ?Math.max(z0,0):z0, qz1=positiveZ?z1:Math.min(z1,0);
            if (qx1 <= qx0 || qz1 <= qz0) return;
            renderBounds(pose,buffer,qx0,y0,qz0,qx1,y1,qz1,scale,originX,originY,originZ,light,alpha);
        }

        private void renderBounds(PoseStack.Pose pose, VertexConsumer buffer,
            float bx0,float by0,float bz0,float bx1,float by1,float bz1,float scale,
            float originX,float originY,float originZ,int light,int alpha) {
            quad(pose,buffer,bx0,by0,bz0,bx1,by0,bz0,bx1,by1,bz0,bx0,by1,bz0,0,0,-1,scale,originX,originY,originZ,light,alpha);
            quad(pose,buffer,bx1,by0,bz1,bx0,by0,bz1,bx0,by1,bz1,bx1,by1,bz1,0,0,1,scale,originX,originY,originZ,light,alpha);
            quad(pose,buffer,bx0,by0,bz1,bx0,by0,bz0,bx0,by1,bz0,bx0,by1,bz1,-1,0,0,scale,originX,originY,originZ,light,alpha);
            quad(pose,buffer,bx1,by0,bz0,bx1,by0,bz1,bx1,by1,bz1,bx1,by1,bz0,1,0,0,scale,originX,originY,originZ,light,alpha);
            quad(pose,buffer,bx0,by1,bz0,bx1,by1,bz0,bx1,by1,bz1,bx0,by1,bz1,0,1,0,scale,originX,originY,originZ,light,alpha);
            quad(pose,buffer,bx0,by0,bz1,bx1,by0,bz1,bx1,by0,bz0,bx0,by0,bz0,0,-1,0,scale,originX,originY,originZ,light,alpha);
        }

        private void quad(PoseStack.Pose pose, VertexConsumer buffer,
            float ax,float ay,float az,float bx,float by,float bz,float cx,float cy,float cz,float dx,float dy,float dz,
            float nx,float ny,float nz,float scale,float originX,float originY,float originZ,int light,int alpha) {
            float inset=0.004F, tile=1F/3F;
            float u0=(materialIndex%3)*tile+inset, v0=(materialIndex/3)*tile+inset;
            float u1=(materialIndex%3+1)*tile-inset, v1=(materialIndex/3+1)*tile-inset;
            vertex(pose,buffer,ax,ay,az,nx,ny,nz,u0,v1,scale,originX,originY,originZ,light,alpha);
            vertex(pose,buffer,bx,by,bz,nx,ny,nz,u1,v1,scale,originX,originY,originZ,light,alpha);
            vertex(pose,buffer,cx,cy,cz,nx,ny,nz,u1,v0,scale,originX,originY,originZ,light,alpha);
            vertex(pose,buffer,dx,dy,dz,nx,ny,nz,u0,v0,scale,originX,originY,originZ,light,alpha);
        }

        private void vertex(PoseStack.Pose pose, VertexConsumer buffer, float x,float y,float z,
            float nx,float ny,float nz,float u,float v,float scale,float originX,float originY,float originZ,int light,int alpha) {
            float px=x-ox, py=y-oy, pz=z-oz;
            float py1=py*cosX-pz*sinX, pz1=py*sinX+pz*cosX;
            float px2=px*cosY+pz1*sinY, pz2=-px*sinY+pz1*cosY;
            float px3=px2*cosZ-py1*sinZ, py3=px2*sinZ+py1*cosZ;
            float nny=ny*cosX-nz*sinX, nnz=ny*sinX+nz*cosX;
            float nnx2=nx*cosY+nnz*sinY, nnz2=-nx*sinY+nnz*cosY;
            float nnx=nnx2*cosZ-nny*sinZ, nny2=nnx2*sinZ+nny*cosZ;
            buffer.addVertex(pose,(px3+ox-originX)*scale,(py3+oy-originY)*scale,(pz2+oz-originZ)*scale)
                .setColor(red,green,blue,alpha).setUv(u,v).setOverlay(OverlayTexture.NO_OVERLAY)
                .setLight(emissive?0xF000F0:light).setNormal(pose,nnx,nny2,nnz2);
        }
    }
