    public static void renderQuarter(final PoseStack.Pose pose, final VertexConsumer buffer,
        final Model model, final float scale, final float originX, final float originY,
        final float originZ, final int light, final int alpha,
        final float minimumCenterY, final float maximumCenterY, final int quarter) {
        if (quarter < 0 || quarter > 3) throw new IllegalArgumentException("quarter must be 0..3");
        for (Cube cube : cubes(model)) {
            float centerY = (cube.y0 + cube.y1) * 0.5F;
            if (centerY >= minimumCenterY && centerY <= maximumCenterY)
                cube.renderQuarter(pose, buffer, scale, originX, originY, originZ, light, alpha, quarter);
        }
    }

